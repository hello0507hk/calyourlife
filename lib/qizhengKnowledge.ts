-二十八星宿是星體移動的客棧，環布在星體周圍。
東方青龍七宿：角木蛟、亢金龍、氐土駱、房日兔、心月狐、尾火虎、箕水豹；
北方玄武七宿：斗木獬、牛金牛、女土蝠、虛日鼠、危月燕、室火豬、壁水貐；
西方白虎七宿：奎木狼、婁金狗、胃土雉、昂日雞、畢月烏、觜火猴、參水猿；
南方朱雀七宿：井木犴、鬼金羊、柳土獐、星日馬、張月鹿、翼火蛇、軫水蚓。
星體與二十八星宿
-經：二十八星宿為經，如角木、斗木、奎木、井木在天同為一經，為同經。
-緯：緯為星體在二十八星宿之間，連結貫串。
-經剋緯：如土在井木，井木為木屬性，木能剋土，土星落在井木，是井木度剋了土星，是為經剋緯。
-緯剋經：如土在參水度，參水度是水屬性，土能剋水，土星落參水，是土星剋度，是為緯剋經。
-升殿：星體進入同屬性的星宿稱為升殿。
-躔泄：星體在自己所生之星宿度，為泄出去的能量。如：金星在軫、箕、壁、參四水度，金星生水，是泄金星之氣，無力。
-失躔：失躔是星體進入剋自己的星宿度：木在四金度，火在四水度，土在四木度、金在四火度、水在四土度，失躔傷星體。
-居嗔：星體在自己所剋之度：木在四土度，水在四火度，土在四水度，金在四木度，火在四金度，居嗔傷星度。
-受生：星體在生我的星度內：木在四水度，火在四木度，水在四金度，金在四土度，土在四火度。
二十八星宿的應用
-星體各有陰陽五行屬性，而十二星宮和二十八宿也各有五行屬性，他們之間互相感應，相互作用。
-星宿主要用在運程上，走限度的時候，就會著重以星宿為主，換星宿的時候，往往也會帶來運勢大幅度的變化。而且不同的星宿都有自己的屬性，這些屬性的星宿可以指同屬性宮的事情，走限的時候，作用就會非常大。在一個宮行大限的時候就會分出不同的生活領域，以及不同運勢。
