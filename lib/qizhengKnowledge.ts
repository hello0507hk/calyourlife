一星滿用。
-我們在星盤中找一顆星，這個星是與三主相關，而且是一顆有用的星，那麼我們就要深入研究這顆星，這星體是夜星還是晝星，四時能量如何，是否受制，掌握什麼宮位，化曜是什麼，最後配合神煞。
