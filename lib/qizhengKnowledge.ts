論三主︰命宮主、命度主、身度主
-命宮主可簡稱命主。
-命宮強大而命度弱、命度強而命宮衰弱都不完美，必須要命宮命度二個主星都要強大，這樣就是盡善盡美了。
-什麼是強？是什麼是弱？強弱是用星體的生剋以及是否廟旺升殿來做一個基本的區別。
命宮主、命度主論：
-命宮主和命度主都強，那麼不貴顯也會富裕；命宮、度主都弱，就會容易貧賤。如果命宮、命度主有一強一弱，就會有不同的得失，需要詳細參看。也就是宮和度都強，那麼內外都好；兩者旺一，內外各自不同；兩者都差，那麼本命的整體情況就相對弱了。
-果老仙說：「要看枯榮唯看月。」
-經典上也說：宮身度主喜朝陽，三主高強福壽昌，恩授不需來輔助，也應富貴始終良。
身度主論：
-人出生在世間，有命亦有身體，命度主是因為太陽而定，身主是因為月亮而產生。所以，就以月亮所在的星宿度的度主為身度主。我們身體的生長要得到身度主星的元氣，所以，剛剛出生時月亮所在星宿度最關緊要。
-身度主、命度主二主自相刑剋不為忌諱。
