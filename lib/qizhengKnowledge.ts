-冬春時木喜見火羅。春天木主生長之象，萬物開始有了生機。在剛剛進入農曆一月時，寒意未退，那麼仍需要火羅來暖。如果一月的木星有水孛相伴，因為太冷，冷水容易損到木的枝葉和根，這個人就會容易生病，或者精力不旺盛。春末夏初之木，有枝有葉，有條有幹，農曆的二、三月，已經是春向夏的轉化，那時木已經成，見金則能發福，因為金能雕木，為棟樑之材。
