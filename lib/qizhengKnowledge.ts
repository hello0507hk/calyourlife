當令星與四時論
-一年有四個季節，會出現春生、夏長、秋收，冬藏四種狀態。春夏是一個生長的季節，而秋冬是收穫和納藏的季節，所以春夏為陽，秋冬為陰。
-四季令星：春天為木（農曆一、二月份），夏天為火（農曆四、五月份），秋天為金（農曆七、八月份），冬天為水（農曆十、十一月份）。土星是在每個季節交替時，做為蘊藏的星體，所以農曆三、六、九、十二月份為四季土強，這些星體在各自的季節為最強，稱為得令。
-星體在不同的季節會有不同的能量強弱，這也是真正判斷五星能量強弱的依據。會判斷星體強弱之後，才可以正確的論斷出誰正真剋了誰，誰又制了誰，這個也就是之前我們提到的有些剋並不是真的剋，有些生並不是真的相生。
-每個季節的轉換，土裡都納藏了別的能量，所以四季的土也會各有不同。
-星體在四季有五個不同的強弱之分，稱：旺、相、休、囚、死五個等級。
-春木旺，火相，水休，金囚，土死；
-夏火旺，土相，木休，水囚，金死；
-秋金旺，水相，木休，土囚，火死；
-冬水旺，木相，金休，土囚，火死；
-四季土旺，金相，火休，木囚，水死；
-當令星所生的星體叫子星，那麼木會生火，火為第二強。木星會漸漸向火星轉化，因為是一個往夏天走的狀態。然後是生木的水排第三。剋木的金排第四，而被木所剋的土為最弱。這樣就出現了五個不同的強弱之分，稱：旺、相、休、囚、死五個等級。旺是指當令星，火為木所生則為相，木最旺時水星可以休息了，木最旺而金無力剋木則稱囚，土遇到木旺則被剋無力而死。
令星的好處︰
-萬物非時不生，觀星非時不驗，因其時令察其盛衰，則禍福輕重自有稱量於其間矣。
-命主為當令星，那麼本身就得了天時，個人的能力和精力都會很強大。看星盤主要就是看能量，如果命宮主、命度主有其一為當令星，必然在某一方面能有所成就。特別是命度主，因為命度主更貼近於自己，命宮主當令也自然會有一定的成就，這種就叫得時。再有如果出生時命盤的恩星為當令星，也很好。恩星當令就會不斷的滋生，就會是一個不斷發展前進的狀態。
-命主屬當令或相，那麼這個盤的能量就會很強。看盤要看是否得時得地，首先看命宮主、命度主是否當令或相，恩星也要強，其次看星體的晝夜之分，若是日生人，且命主或用星屬於晝星，那會更好。
-日月不好，但是命主、度主當令，那麼就完全要靠自己，靠不了別人。那麼要懂得不斷的提升自己的特長，不能懶惰，因為外在沒有助力，完全靠自身本事。如果一個人是日月好，命主不怎麼樣，那麼他就需要多出門交朋友，會認識很多能幫到他的貴人。
-當令星不宜再生，也不宜泄，因為他已經是一個最好、最適宜的時候了。被生的令星容易自大，會樹大招風；如令星泄到無用的地方，就容易沉迷在一些無用的事情上。
-令星宜受制約，最忌洩氣。一個人命主當令，那麼他的能力很強，最怕這個能力泄到了不好的地方，這個人就容易玩物喪志。所以令星最好是有星體來剋，因為能力強，困難是無法阻擋的，他能解決和承受的，在這裡受剋反而更好，會越挫越勇，在困難中獲得更多的經驗和成長。
-令星宜受剋，冬生水命人例外。
-日月本身沒有洩氣，因為日月本身是沒有生剋的，除非他相伴的星比較多又代表了不好的事情，通常不會論日月的洩氣。
