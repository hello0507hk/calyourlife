四時：
四時的作用主要在於分清楚星體的能量強弱，四時是論盤首要得考慮的地方，先把星體強弱分出來。四時是分辨星體的能量強弱，晝夜是分清星體的作用強弱，展現陰陽得宜，提升格局層次之用。
